import { neon } from "@neondatabase/serverless";

import type { BoardRepository } from "./repository";
import { createSeedData } from "./seed";
import type { Comment, Post, PostSummary } from "./types";

type Row = Record<string, unknown>;

// 같은 DB를 쓰는 다른 앱과 겹치지 않도록 테이블 이름에 접두어를 붙입니다.
const SCHEMA = [
  `CREATE TABLE IF NOT EXISTS board_posts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    content text NOT NULL,
    author text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    views integer NOT NULL DEFAULT 0
  )`,
  `CREATE TABLE IF NOT EXISTS board_comments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id integer NOT NULL REFERENCES board_posts(id) ON DELETE CASCADE,
    author text NOT NULL,
    content text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX IF NOT EXISTS board_comments_post_id_idx ON board_comments (post_id)`,
];

const iso = (value: unknown) => new Date(value as string | Date).toISOString();

function toPost(row: Row): Post {
  return {
    id: Number(row.id),
    title: String(row.title),
    content: String(row.content),
    author: String(row.author),
    createdAt: iso(row.created_at),
    updatedAt: iso(row.updated_at),
    views: Number(row.views),
  };
}

function toComment(row: Row): Comment {
  return {
    id: Number(row.id),
    postId: Number(row.post_id),
    author: String(row.author),
    content: String(row.content),
    createdAt: iso(row.created_at),
  };
}

/**
 * Neon(PostgreSQL)에 저장하는 구현입니다. 처음 쓰일 때 테이블을 만들고,
 * 게시글이 하나도 없으면 샘플 데이터를 넣습니다.
 */
export function createPostgresRepository(
  connectionString: string,
): BoardRepository {
  const sql = neon(connectionString);
  let ready: Promise<void> | null = null;

  async function setup() {
    for (const statement of SCHEMA) await sql.query(statement);

    const { posts, comments } = createSeedData();
    // 여러 서버가 동시에 시작해도 한 번만 시드되도록 트랜잭션 잠금을 겁니다.
    await sql.transaction([
      sql`SELECT pg_advisory_xact_lock(hashtext('board_seed'))`,
      sql.query(
        `WITH seeded AS (
           INSERT INTO board_posts (id, title, content, author, created_at, updated_at, views)
           SELECT * FROM jsonb_to_recordset($1::jsonb) AS p(
             id integer, title text, content text, author text,
             "createdAt" timestamptz, "updatedAt" timestamptz, views integer)
           WHERE NOT EXISTS (SELECT 1 FROM board_posts)
           RETURNING id
         )
         INSERT INTO board_comments (id, post_id, author, content, created_at)
         SELECT c.* FROM jsonb_to_recordset($2::jsonb) AS c(
           id integer, "postId" integer, author text, content text, "createdAt" timestamptz)
         WHERE EXISTS (SELECT 1 FROM seeded)`,
        [JSON.stringify(posts), JSON.stringify(comments)],
      ),
      // 시드에서 id를 직접 넣었으므로 다음 id가 이어지도록 맞춥니다.
      sql`SELECT setval(pg_get_serial_sequence('board_posts', 'id'), GREATEST((SELECT max(id) FROM board_posts), 1))`,
      sql`SELECT setval(pg_get_serial_sequence('board_comments', 'id'), GREATEST((SELECT max(id) FROM board_comments), 1))`,
    ]);
  }

  /** 모든 쿼리 전에 테이블 준비가 끝났는지 확인합니다. 실패하면 다음 요청에서 다시 시도합니다. */
  async function db() {
    ready ??= setup().catch((error) => {
      ready = null;
      throw error;
    });
    await ready;
    return sql;
  }

  return {
    async listPosts({ query = "", field = "all", page = 1, pageSize = 10 }) {
      const sql = await db();
      const needle = query.trim().toLowerCase();
      const conditions = {
        all: "(strpos(lower(title), $1) > 0 OR strpos(lower(content), $1) > 0)",
        title: "strpos(lower(title), $1) > 0",
        content: "strpos(lower(content), $1) > 0",
      };
      const where = needle ? `WHERE ${conditions[field]}` : "";
      const params = needle ? [needle] : [];

      const [{ count }] = await sql.query(
        `SELECT count(*)::int AS count FROM board_posts ${where}`,
        params,
      );
      const total = Number(count);
      const totalPages = Math.max(1, Math.ceil(total / pageSize));
      const current = Math.min(Math.max(1, page), totalPages);

      const rows = await sql.query(
        `SELECT p.id, p.title, p.author, p.created_at, p.updated_at, p.views,
                (SELECT count(*)::int FROM board_comments c WHERE c.post_id = p.id) AS comment_count
           FROM board_posts p ${where}
          ORDER BY p.id DESC
          LIMIT ${pageSize} OFFSET ${(current - 1) * pageSize}`,
        params,
      );
      const items: PostSummary[] = rows.map((row) => ({
        id: Number(row.id),
        title: String(row.title),
        author: String(row.author),
        createdAt: iso(row.created_at),
        updatedAt: iso(row.updated_at),
        views: Number(row.views),
        commentCount: Number(row.comment_count),
      }));

      return { items, total, page: current, pageSize, totalPages };
    },

    async getPost(id) {
      const sql = await db();
      const [row] = await sql`SELECT * FROM board_posts WHERE id = ${id}`;
      return row ? toPost(row) : null;
    },

    async createPost({ title, content, author }) {
      const sql = await db();
      const [row] = await sql`
        INSERT INTO board_posts (title, content, author)
        VALUES (${title}, ${content}, ${author})
        RETURNING *`;
      return toPost(row);
    },

    async updatePost(id, { title, content }) {
      const sql = await db();
      const [row] = await sql`
        UPDATE board_posts
           SET title = ${title}, content = ${content}, updated_at = now()
         WHERE id = ${id}
        RETURNING *`;
      return row ? toPost(row) : null;
    },

    async deletePost(id) {
      const sql = await db();
      const rows =
        await sql`DELETE FROM board_posts WHERE id = ${id} RETURNING id`;
      return rows.length > 0;
    },

    async incrementViews(id) {
      const sql = await db();
      const [row] = await sql`
        UPDATE board_posts SET views = views + 1 WHERE id = ${id} RETURNING views`;
      return row ? Number(row.views) : null;
    },

    async listComments(postId) {
      const sql = await db();
      const rows = await sql`
        SELECT * FROM board_comments WHERE post_id = ${postId} ORDER BY id`;
      return rows.map(toComment);
    },

    async createComment(postId, { author, content }) {
      const sql = await db();
      const [row] = await sql`
        INSERT INTO board_comments (post_id, author, content)
        SELECT id, ${author}, ${content} FROM board_posts WHERE id = ${postId}
        RETURNING *`;
      return row ? toComment(row) : null;
    },

    async deleteComment(postId, commentId) {
      const sql = await db();
      const rows = await sql`
        DELETE FROM board_comments
         WHERE id = ${commentId} AND post_id = ${postId}
        RETURNING id`;
      return rows.length > 0;
    },
  };
}
